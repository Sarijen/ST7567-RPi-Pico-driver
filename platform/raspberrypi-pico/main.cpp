struct picoBoard {
  static void cs(bool enable);
  static void dc(bool mode);
  static void rst(bool reset);
  static void spi_write(const uint8_t data);
  static void delay_us(const uint8_t duration);
};


int main() {
  gpio_init(DC_PIN);
  gpio_init(CS_PIN);
  gpio_init(RST_PIN);
  gpio_init(BACKLIGHT_PIN);

  gpio_set_dir(DC_PIN, GPIO_OUT);
  gpio_set_dir(CS_PIN, GPIO_OUT);
  gpio_set_dir(RST_PIN, GPIO_OUT);
  gpio_set_dir(BACKLIGHT_PIN, GPIO_OUT);

  gpio_put(CS_PIN, GPIO_HIGH); 
  gpio_put(DC_PIN, GPIO_LOW);
  gpio_put(RST_PIN, GPIO_HIGH);
  gpio_put(BACKLIGHT_PIN, GPIO_HIGH);

  spi_init(SPI_ID, sclk_freq);

  gpio_set_function(MOSI_PIN, GPIO_FUNC_SPI);
  gpio_set_function(SCLK_PIN, GPIO_FUNC_SPI);
  spi_set_format(
    SPI_ID,
    8,
    SPI_CPOL_0,  
    SPI_CPHA_0,   
    SPI_MSB_FIRST  
  );


  ST7567<picoBoard> st;
  st.init();

  st.clearFramebuffer();
  st.drawRectangle(0, 0, 128, 64);

  st.drawString(2, 4, font_10x16, "ST7567");
  st.drawString(3, 20, font_5x8, "AbBbCcDdEe");
  st.drawString(3, 29, font_5x8, "1234567890");
  st.drawString(3, 38, font_5x8, "!?<>()@#*%");
  st.drawString(3, 47, font_10x16, "C++20");

  st.drawImage(63, 0, 63, 64, vim_logo);

  st.sendFramebuffer();

  return 0;
}


void picoBoard::cs(bool enable) {
  gpio_put(CS_PIN, enable);
};


void picoBoard::dc(bool mode) {
  gpio_put(DC_PIN, mode);
};


void picoBoard::rst(bool reset) {
  gpio_put(RST_PIN, reset);
};


void picoBoard::spi_write(const uint8_t data) {
  spi_write_blocking(SPI_ID, &data, 1);
};


void picoBoard::delay_us(const uint8_t duration) {
  sleep_us(duration);
};
